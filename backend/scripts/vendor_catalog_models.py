"""
Copy catalog GLBs into hall/models/catalog/ for same-origin Live Scan / KG.

No Cloudflare/R2/Supabase. Vercel/GitHub reject files over 100MB.

Default: compressed copies from backend/data/models-public/models.
--raw: original photogrammetry files (filenames may be AG028-AG029.glb).

Usage:
  python backend/scripts/vendor_catalog_models.py
  python backend/scripts/vendor_catalog_models.py --raw --src "D:\\STORAGE\\Downloads\\Andrew Gonzales (AG)-20261022T042645Z-1-001\\Andrew Gonzales (AG)"
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
REPO = BACKEND.parent
SRC = BACKEND / "data" / "models-public" / "models"
DEST = REPO / "hall" / "models" / "catalog"
IDS_JS = REPO / "hall" / "scripts" / "catalog-glb-ids.js"
CODE_RE = re.compile(r"([A-Z]{1,4}\d{1,4})", re.I)
DEFAULT_RAW = Path(
    r"D:\STORAGE\Downloads\Andrew Gonzales (AG)-20261022T042645Z-1-001\Andrew Gonzales (AG)"
)


def codes_from_name(name: str) -> list[str]:
    found: list[str] = []
    seen: set[str] = set()
    for match in CODE_RE.finditer(Path(name).stem):
        code = re.sub(r"\s+", "", (match.group(1) or "").upper())
        if not code or code in seen:
            continue
        seen.add(code)
        found.append(code)
    return found


def write_manifest(dest: Path, codes: list[str]) -> None:
    (dest / "manifest.json").write_text(json.dumps({"files": codes}, indent=2) + "\n", encoding="utf-8")
    IDS_JS.write_text(
        "/* Generated by backend/scripts/vendor_catalog_models.py — do not edit by hand. */\n"
        "export const CATALOG_GLB_CODES = Object.freeze(" + json.dumps(codes) + ");\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", default="")
    parser.add_argument("--dest", default=str(DEST))
    parser.add_argument("--budget-mb", type=float, default=0)
    parser.add_argument("--max-file-mb", type=float, default=0)
    parser.add_argument(
        "--raw",
        action="store_true",
        help="Copy original uncompressed GLBs (map AG028-AG029.glb onto both accession codes).",
    )
    args = parser.parse_args()
    raw = args.raw
    src = Path(args.src) if args.src else (DEFAULT_RAW if raw else SRC)
    dest = Path(args.dest)
    budget_mb = args.budget_mb or (2000 if raw else 520)
    max_file_mb = args.max_file_mb or (90 if raw else 40)
    if not src.is_dir():
        print(f"Missing models at {src}.", file=__import__("sys").stderr)
        return 1

    budget = int(budget_mb * 1024 * 1024)
    max_file = int(max_file_mb * 1024 * 1024)
    files = sorted(
        [path for path in src.glob("*.glb") if path.is_file()],
        key=lambda path: (path.stat().st_size, path.name),
    )
    dest.mkdir(parents=True, exist_ok=True)
    for old in dest.glob("*.glb"):
        old.unlink()

    codes: list[str] = []
    total = 0
    skipped_large = 0
    skipped_budget = 0
    for path in files:
        size = path.stat().st_size
        names = codes_from_name(path.name) if raw else [path.stem.upper()]
        if not names:
            names = [path.stem.upper()]
        copies = max(1, len(names))
        if size > max_file:
            skipped_large += 1
            continue
        if total + size * copies > budget:
            skipped_budget += 1
            continue
        for code in names:
            shutil.copy2(path, dest / f"{code}.glb")
            codes.append(code)
        total += size * copies

    write_manifest(dest, codes)
    print(
        f"vendored {len(codes)} GLBs ({total / (1024 * 1024):.1f} MB) into {dest} "
        f"(raw={raw}; skipped {skipped_large} over {max_file_mb:g}MB/file, "
        f"{skipped_budget} over {budget_mb:g}MB budget)"
    )
    print("Live Scan / KG overlay load /models/catalog/{CODE}.glb from the hall host (no R2).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
