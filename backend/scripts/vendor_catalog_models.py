"""
Copy compressed laptop GLBs into hall/models/catalog/ for same-origin Live Scan / KG.

No Cloudflare/R2/Supabase. Vercel/GitHub reject files over 100MB; this copies every
compressed model under --max-file-mb until --budget-mb (smallest first so the
constellation can fill with more objects).

Usage:
  python backend/scripts/vendor_catalog_models.py
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
REPO = BACKEND.parent
SRC = BACKEND / "data" / "models-public" / "models"
DEST = REPO / "hall" / "models" / "catalog"
IDS_JS = REPO / "hall" / "scripts" / "catalog-glb-ids.js"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", default=str(SRC))
    parser.add_argument("--dest", default=str(DEST))
    parser.add_argument("--budget-mb", type=float, default=520)
    parser.add_argument("--max-file-mb", type=float, default=40)
    args = parser.parse_args()
    src = Path(args.src)
    dest = Path(args.dest)
    if not src.is_dir():
        print(f"Missing compressed models at {src}. Run npm run models:compress first.")
        return 1

    budget = int(args.budget_mb * 1024 * 1024)
    max_file = int(args.max_file_mb * 1024 * 1024)
    files = sorted(
        [path for path in src.glob("*.glb") if path.is_file()],
        key=lambda path: (path.stat().st_size, path.name),
    )
    dest.mkdir(parents=True, exist_ok=True)
    for old in dest.glob("*.glb"):
        old.unlink()

    chosen: list[Path] = []
    total = 0
    skipped_large = 0
    for path in files:
        size = path.stat().st_size
        if size > max_file:
            skipped_large += 1
            continue
        if total + size > budget:
            continue
        shutil.copy2(path, dest / path.name)
        chosen.append(path)
        total += size

    codes = [path.stem.upper() for path in chosen]
    (dest / "manifest.json").write_text(json.dumps({"files": codes}, indent=2) + "\n", encoding="utf-8")
    IDS_JS.write_text(
        "/* Generated by backend/scripts/vendor_catalog_models.py — do not edit by hand. */\n"
        "export const CATALOG_GLB_CODES = Object.freeze(" + json.dumps(codes) + ");\n",
        encoding="utf-8",
    )
    skipped = len(files) - len(chosen)
    print(
        f"vendored {len(chosen)} GLBs ({total / (1024 * 1024):.1f} MB) into {dest} "
        f"(skipped {skipped} — {skipped_large} over {args.max_file_mb:g}MB/file, "
        f"{skipped - skipped_large} over {args.budget_mb:g}MB budget)"
    )
    print("Live Scan will load /models/catalog/{CODE}.glb from the hall host (no R2).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
